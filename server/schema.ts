/**
 * Auth identity'lar — canonical user (users.id) ↔ provider akkaunt xaritasi
 * (multi-provider auth). PK (provider, provider_uid): bitta Telegram akkaunt /
 * telefon raqam / email faqat BITTA user'ga tegishli bo'ladi.
 * `password_hash` provider='phone' va provider='email' uchun (scrypt "salt:hash" hex).
 * OAuth provider'lar (google, apple) parolsiz.
 * Linking: bitta user'ga bir necha identity (masalan telegram + phone + email) ulansa
 * bo'ladi — barcha qatorlar bir xil user_id'ga ishora qiladi.
 */
export const authIdentities = pgTable('auth_identities', {
  provider:     text('provider').notNull(),
  providerUid:  text('provider_uid').notNull(),
  userId:       text('user_id').notNull().references(() => users.id, { onDelete: 'cascade', onUpdate: 'cascade' }),
  passwordHash: text('password_hash'),
  createdAt:    timestamp('created_at').defaultNow().notNull(),
}, (t) => [
  primaryKey({ columns: [t.provider, t.providerUid] }),
  index('idx_auth_identities_user').on(t.userId),
  check('chk_auth_identities_provider', sql`${t.provider} IN ('telegram','phone','email','google','apple')`),
])

