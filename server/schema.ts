/**
 * Password reset tokens — consumed via used_at timestamp (not deleted on use).
 * Multiple active tokens per user allowed for concurrent reset from different devices.
 */
export const passwordResetTokens = pgTable('password_reset_tokens', {
  token:     text('token').primaryKey(),
  userId:    text('user_id').notNull().references(() => users.id, { onDelete: 'cascade', onUpdate: 'cascade' }),
  expiresAt: timestamp('expires_at').notNull(),
  usedAt:    timestamp('used_at'),
  createdAt: timestamp('created_at').defaultNow().notNull(),
}, (t) => [
  // Composite for checking expiry per user
  index('idx_password_reset_user_expires').on(t.userId, t.expiresAt),
  // Partial index for unused tokens (validation query pattern)
  index('idx_password_reset_unused').on(t.userId).where(sql`${t.usedAt} IS NULL`),
  // Cleanup cron index
  index('idx_password_reset_expires').on(t.expiresAt),
  check('chk_password_reset_token_len', sql`length(${t.token}) = 64`),
  check('chk_password_reset_expires', sql`${t.expiresAt} > ${t.createdAt}`),
])

